'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('NTPUOne/AIAssistant/AILoginDiagnostics.swift','utf8').split('static let source = #"""')[1].split('"""#')[0];
const secret = 'fixture-sensitive-data';
const field = (type,name,autocomplete='') => Object.defineProperty({type,name,autocomplete},'value',{get(){throw Error('INPUT VALUE MUST NOT BE READ');}});
const inputs = [field('text','username','username'),field('password','password'),field('hidden','SAMLResponse')];
const form = {method:'post',getAttribute:()=>`https://sso.ntpu.edu.tw/auth/login/411000000?password=${secret}`,querySelectorAll:()=>inputs};
const context = {URL,location:{protocol:'https:',hostname:'sso.ntpu.edu.tw',pathname:'/login',href:'https://sso.ntpu.edu.tw/login'},document:{forms:[form],querySelector:()=>null,querySelectorAll:()=>inputs}};
const report = vm.runInNewContext(source,context);
assert.equal(report.forms[0].passwordFields,1);
assert.equal(report.forms[0].usernameFields,1);
assert.equal(report.forms[0].hasSAML,true);
assert.equal(report.forms[0].actionPathShape,'/auth/login/:route');
assert(!JSON.stringify(report).includes(secret));
assert(!JSON.stringify(report).includes('411000000'));
context.location.hostname='untrusted.example';
assert.equal(vm.runInNewContext(source,context),null);
console.log('AI login structural diagnostic without reading input values: PASS');
